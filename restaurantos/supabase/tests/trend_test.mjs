import { daysInRange, previousRange, percentChange } from '/tmp/h/trendMath.mjs'
let pass = 0, fail = 0
const eq = (name, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); ok ? pass++ : fail++; console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${ok ? '' : `  got ${JSON.stringify(got)} want ${JSON.stringify(want)}`}`) }
eq('a week (15–21 Sep) is 7 days', daysInRange('2026-09-15', '2026-09-21'), 7)
eq('a single day is 1 day', daysInRange('2026-09-21', '2026-09-21'), 1)
eq('30-day preset span', daysInRange('2026-08-23', '2026-09-21'), 30)
eq('backwards range -> 0', daysInRange('2026-09-21', '2026-09-15'), 0)
eq('half-typed (empty) date -> 0', daysInRange('', '2026-09-21'), 0)
eq('garbage date -> 0', daysInRange('not-a-date', '2026-09-21'), 0)
eq('previous of a week', previousRange('2026-09-15', '2026-09-21'), { from: '2026-09-08', to: '2026-09-14' })
eq('previous of a single day', previousRange('2026-09-21', '2026-09-21'), { from: '2026-09-20', to: '2026-09-20' })
eq('previous across a MONTH boundary', previousRange('2026-10-02', '2026-10-08'), { from: '2026-09-25', to: '2026-10-01' })
eq('previous across a YEAR boundary', previousRange('2027-01-03', '2027-01-09'), { from: '2026-12-27', to: '2027-01-02' })
eq('previous across LEAP day (2028)', previousRange('2028-03-02', '2028-03-08'), { from: '2028-02-24', to: '2028-03-01' })
eq('previous of a 30-day range', previousRange('2026-08-23', '2026-09-21'), { from: '2026-07-24', to: '2026-08-22' })
eq('previous of a 90-day range is also 90 days', daysInRange(...Object.values(previousRange('2026-06-24', '2026-09-21'))), 90)
eq('previous of a backwards range -> null', previousRange('2026-09-21', '2026-09-15'), null)
eq('+50% ', percentChange(150, 100), 50)
eq('-25% ', percentChange(75, 100), -25)
eq('0 -> something: no percent (not Infinity)', percentChange(100, 0), null)
eq('0 -> 0: no percent (not NaN)', percentChange(0, 0), null)
eq('NaN input -> null', percentChange(NaN, 100), null)
eq('total drop to zero = -100%', percentChange(0, 500), -100)
console.log(`\n${pass} passed, ${fail} failed`)
process.exit(fail ? 1 : 0)
